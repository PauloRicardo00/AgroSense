CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL CHECK (btrim(nome) <> ''),
    descricao VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_setor_nome ON setor (lower(btrim(nome)));

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    email VARCHAR(160) NOT NULL CHECK (btrim(email) <> ''),
    senha_hash VARCHAR(255) NOT NULL CHECK (btrim(senha_hash) <> ''),
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('OPERADOR', 'TECNICO', 'GESTOR', 'ADMIN')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_usuario_email ON usuario (lower(btrim(email)));

CREATE TABLE tecnico_setor (
    tecnico_id BIGINT NOT NULL REFERENCES usuario(id),
    setor_id BIGINT NOT NULL REFERENCES setor(id),
    habilitado BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (tecnico_id, setor_id)
);

CREATE TABLE maquina (
    id VARCHAR(30) PRIMARY KEY CHECK (btrim(id) <> ''),
    setor_id BIGINT NOT NULL REFERENCES setor(id),
    nome VARCHAR(120) NOT NULL CHECK (btrim(nome) <> ''),
    descricao VARCHAR(500),
    ativa BOOLEAN NOT NULL DEFAULT TRUE,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_maquina_setor ON maquina(setor_id);

CREATE TABLE leitura (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id VARCHAR(100) UNIQUE CHECK (message_id IS NULL OR btrim(message_id) <> ''),
    machine_id VARCHAR(30) NOT NULL REFERENCES maquina(id),
    origem VARCHAR(20) NOT NULL DEFAULT 'simulado' CHECK (origem = 'simulado'),
    medida_em TIMESTAMPTZ,
    recebida_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    tipo VARCHAR(1) NOT NULL CHECK (tipo IN ('L', 'M', 'H')),
    air_temperature DOUBLE PRECISION NOT NULL,
    process_temperature DOUBLE PRECISION NOT NULL,
    rotational_speed DOUBLE PRECISION NOT NULL,
    torque DOUBLE PRECISION NOT NULL,
    tool_wear DOUBLE PRECISION NOT NULL,
    score_falha DOUBLE PRECISION CHECK (score_falha BETWEEN 0 AND 1),
    limiar DOUBLE PRECISION CHECK (limiar BETWEEN 0 AND 1),
    falha BOOLEAN,
    versao_modelo VARCHAR(50) CHECK (versao_modelo IS NULL OR btrim(versao_modelo) <> ''),
    analisada_em TIMESTAMPTZ,
    status_analise VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status_analise IN ('PENDENTE', 'OK', 'INDISPONIVEL')),
    CONSTRAINT uq_leitura_id_maquina UNIQUE (id, machine_id),
    CONSTRAINT ck_leitura_valores CHECK (
        air_temperature > 0 AND air_temperature < 'Infinity'::DOUBLE PRECISION
        AND process_temperature > 0 AND process_temperature < 'Infinity'::DOUBLE PRECISION
        AND rotational_speed > 0 AND rotational_speed < 'Infinity'::DOUBLE PRECISION
        AND torque > 0 AND torque < 'Infinity'::DOUBLE PRECISION
        AND tool_wear >= 0 AND tool_wear < 'Infinity'::DOUBLE PRECISION
    ),
    CONSTRAINT ck_leitura_resultado CHECK (
        status_analise <> 'OK' OR (
            score_falha IS NOT NULL AND limiar IS NOT NULL AND falha IS NOT NULL
            AND versao_modelo IS NOT NULL AND analisada_em IS NOT NULL
            AND falha = (score_falha >= limiar)
        )
    )
);
CREATE INDEX ix_leitura_recebida ON leitura(recebida_em DESC, id DESC);
CREATE INDEX ix_leitura_maquina_recebida ON leitura(machine_id, recebida_em DESC, id DESC);
CREATE INDEX ix_leitura_maquina_medida ON leitura(machine_id, medida_em DESC NULLS LAST, recebida_em DESC, id DESC);
CREATE INDEX ix_leitura_pendente ON leitura(recebida_em) WHERE status_analise = 'PENDENTE';

CREATE TABLE mensagem_rejeitada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recebida_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    topico VARCHAR(200),
    motivo VARCHAR(40) NOT NULL CHECK (btrim(motivo) <> ''),
    detalhe VARCHAR(500),
    message_id VARCHAR(100),
    machine_id VARCHAR(100),
    payload VARCHAR(2000)
);
CREATE INDEX ix_rejeitada_recebida ON mensagem_rejeitada(recebida_em DESC);

CREATE TABLE alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maquina_id VARCHAR(30) NOT NULL REFERENCES maquina(id),
    status VARCHAR(20) NOT NULL DEFAULT 'ABERTO'
        CHECK (status IN ('ABERTO', 'RECONHECIDO', 'ENCERRADO')),
    aberto_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultima_ocorrencia_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    encerrado_em TIMESTAMPTZ,
    leitura_inicial_id BIGINT NOT NULL,
    ultima_leitura_id BIGINT NOT NULL,
    score_maximo DOUBLE PRECISION NOT NULL CHECK (score_maximo BETWEEN 0 AND 1),
    versao_modelo VARCHAR(50) NOT NULL CHECK (btrim(versao_modelo) <> ''),
    reconhecido_por BIGINT REFERENCES usuario(id),
    reconhecido_em TIMESTAMPTZ,
    observacao VARCHAR(1000),
    UNIQUE (id, maquina_id),
    FOREIGN KEY (leitura_inicial_id, maquina_id) REFERENCES leitura(id, machine_id),
    FOREIGN KEY (ultima_leitura_id, maquina_id) REFERENCES leitura(id, machine_id),
    CONSTRAINT ck_alerta_reconhecimento CHECK (
        (reconhecido_por IS NULL) = (reconhecido_em IS NULL)
        AND (status <> 'RECONHECIDO' OR reconhecido_por IS NOT NULL)
        AND (status <> 'ABERTO' OR reconhecido_por IS NULL)
    ),
    CONSTRAINT ck_alerta_encerramento CHECK (
        (status = 'ENCERRADO') = (encerrado_em IS NOT NULL)
        AND ultima_ocorrencia_em >= aberto_em
        AND (encerrado_em IS NULL OR encerrado_em >= ultima_ocorrencia_em)
        AND (reconhecido_em IS NULL OR reconhecido_em >= aberto_em)
    )
);
CREATE UNIQUE INDEX ux_alerta_ativo ON alerta(maquina_id) WHERE status <> 'ENCERRADO';
CREATE INDEX ix_alerta_maquina_aberto ON alerta(maquina_id, aberto_em DESC);

CREATE TABLE ordem_servico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero TEXT GENERATED ALWAYS AS ('OS-' || id::TEXT) STORED,
    alerta_id BIGINT NOT NULL,
    maquina_id VARCHAR(30) NOT NULL,
    setor_id BIGINT NOT NULL REFERENCES setor(id),
    titulo VARCHAR(160) NOT NULL CHECK (btrim(titulo) <> ''),
    descricao TEXT NOT NULL CHECK (btrim(descricao) <> ''),
    dados_abertura JSONB NOT NULL CHECK (jsonb_typeof(dados_abertura) = 'object'),
    prioridade VARCHAR(10) NOT NULL DEFAULT 'MEDIA'
        CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    prazo_previsto TIMESTAMPTZ,
    status VARCHAR(30) NOT NULL DEFAULT 'AGUARDANDO_ATRIBUICAO'
        CHECK (status IN ('AGUARDANDO_ATRIBUICAO', 'ABERTA', 'EM_ANDAMENTO', 'CONCLUIDA', 'CANCELADA')),
    modo_atribuicao VARCHAR(10) NOT NULL CHECK (modo_atribuicao IN ('MANUAL', 'AUTOMATICA')),
    criado_por BIGINT NOT NULL REFERENCES usuario(id),
    tecnico_id BIGINT REFERENCES usuario(id),
    atribuido_por BIGINT REFERENCES usuario(id),
    atribuida_em TIMESTAMPTZ,
    criada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizada_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    iniciada_em TIMESTAMPTZ,
    concluida_em TIMESTAMPTZ,
    cancelada_em TIMESTAMPTZ,
    relato_final TEXT,
    FOREIGN KEY (alerta_id, maquina_id) REFERENCES alerta(id, maquina_id),
    CONSTRAINT ck_os_atribuicao CHECK (
        (tecnico_id IS NULL) = (atribuida_em IS NULL)
        AND (tecnico_id IS NULL) = (atribuido_por IS NULL)
        AND (status <> 'AGUARDANDO_ATRIBUICAO' OR tecnico_id IS NULL)
        AND (status NOT IN ('ABERTA', 'EM_ANDAMENTO', 'CONCLUIDA') OR tecnico_id IS NOT NULL)
    ),
    CONSTRAINT ck_os_datas CHECK (
        (status = 'CONCLUIDA') = (concluida_em IS NOT NULL)
        AND (status = 'CANCELADA') = (cancelada_em IS NOT NULL)
        AND (status NOT IN ('EM_ANDAMENTO', 'CONCLUIDA') OR iniciada_em IS NOT NULL)
        AND (iniciada_em IS NULL OR iniciada_em >= criada_em)
        AND (concluida_em IS NULL OR concluida_em >= iniciada_em)
        AND (cancelada_em IS NULL OR cancelada_em >= criada_em)
    )
);
CREATE UNIQUE INDEX ux_os_alerta_ativa ON ordem_servico(alerta_id)
    WHERE status IN ('AGUARDANDO_ATRIBUICAO', 'ABERTA', 'EM_ANDAMENTO');
CREATE INDEX ix_os_tecnico_status ON ordem_servico(tecnico_id, status);
CREATE INDEX ix_os_maquina ON ordem_servico(maquina_id, criada_em DESC);

CREATE TABLE os_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    os_id BIGINT NOT NULL REFERENCES ordem_servico(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    evento VARCHAR(40) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    dados JSONB NOT NULL DEFAULT '{}'::JSONB
);
CREATE INDEX ix_os_historico ON os_historico(os_id, ocorrido_em, id);
